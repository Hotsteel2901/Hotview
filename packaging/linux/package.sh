#!/bin/sh
# Build a ready-to-install Linux package from an already compiled binary.
#
#   packaging/linux/package.sh arch        -> hotview-<ver>-1-<arch>.pkg.tar.zst
#   packaging/linux/package.sh debian      -> hotview_<ver>_<arch>.deb
#
# Environment:
#   HOTVIEW_VERSION   version string (default: packaging/version.sh)
#   HOTVIEW_BINARY    path to the release binary (default: target/release/hotview)
#   HOTVIEW_OUTDIR    output directory (default: dist)
#   HOTVIEW_ARCH      package architecture (default: uname -m)
#   HOTVIEW_DEB_ARCH  Debian architecture (default: amd64 on x86_64)
#   HOTVIEW_PKGREL    Arch pkgrel (default: 1)
set -eu

fmt=${1:-}
case "$fmt" in
    arch | debian) ;;
    *)
        echo "usage: $0 arch|debian" >&2
        exit 2
        ;;
esac

root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
version=${HOTVIEW_VERSION:-$(sh "$root/packaging/version.sh")}
binary=${HOTVIEW_BINARY:-"$root/target/release/hotview"}
outdir=${HOTVIEW_OUTDIR:-"$root/dist"}
pkgarch=${HOTVIEW_ARCH:-$(uname -m)}
pkgrel=${HOTVIEW_PKGREL:-1}

case "$pkgarch" in
    x86_64 | amd64) debarch=${HOTVIEW_DEB_ARCH:-amd64} ;;
    aarch64 | arm64) debarch=${HOTVIEW_DEB_ARCH:-arm64} ;;
    *) debarch=${HOTVIEW_DEB_ARCH:-$pkgarch} ;;
esac

if [ ! -f "$binary" ]; then
    echo "error: binary not found: $binary" >&2
    echo "build it first with: cargo build --release -p hotview-desktop" >&2
    exit 1
fi
if [ "$version" = "" ]; then
    echo "error: empty version (set HOTVIEW_VERSION)" >&2
    exit 1
fi

mkdir -p "$outdir"
outdir=$(CDPATH= cd -- "$outdir" && pwd)

tmp=$(mktemp -d "${TMPDIR:-/tmp}/hotview-pkg.XXXXXX")
trap 'rm -rf "$tmp"' EXIT INT TERM

stage="$tmp/root"
mkdir -p \
    "$stage/usr/bin" \
    "$stage/usr/share/applications" \
    "$stage/usr/share/metainfo" \
    "$stage/usr/share/licenses/hotview" \
    "$stage/usr/share/doc/hotview"

install -Dm755 "$binary" "$stage/usr/bin/hotview"
install -Dm644 "$root/packaging/linux/hotview.desktop" \
    "$stage/usr/share/applications/hotview.desktop"
install -Dm644 "$root/packaging/linux/hotview.metainfo.xml" \
    "$stage/usr/share/metainfo/com.hotsteel.Hotview.metainfo.xml"
install -Dm644 "$root/LICENSE" "$stage/usr/share/licenses/hotview/LICENSE"
install -Dm644 "$root/packaging/linux/copyright" \
    "$stage/usr/share/doc/hotview/copyright"
install -Dm644 "$root/README.md" "$stage/usr/share/doc/hotview/README.md"

for size in 16 24 32 48 64 128 256 512; do
    install -Dm644 "$root/packaging/icons/hotview-${size}.png" \
        "$stage/usr/share/icons/hicolor/${size}x${size}/apps/hotview.png"
done

# ---------------------------------------------------------------------------
# Arch Linux / pacman package (.pkg.tar.zst)
# ---------------------------------------------------------------------------
build_arch() {
    command -v bsdtar >/dev/null 2>&1 || {
        echo "error: bsdtar (libarchive) is required for Arch packages" >&2
        exit 1
    }
    command -v zstd >/dev/null 2>&1 || {
        echo "error: zstd is required for Arch packages" >&2
        exit 1
    }

    pkgdir="$tmp/arch"
    mkdir -p "$pkgdir"
    cp -a "$stage/." "$pkgdir/"

    installed_size=$(du -sk "$pkgdir/usr" | awk '{print $1 * 1024}')
    builddate=$(date +%s)

    cat >"$pkgdir/.PKGINFO" <<EOF
# Generated by Hotview packaging
pkgname = hotview
pkgbase = hotview
pkgver = $version-$pkgrel
pkgdesc = Fast image and video viewer with GPU rendering
url = https://github.com/Hotsteel2901/Hotview
builddate = $builddate
packager = Hotsteel <hotsteel2901@users.noreply.github.com>
size = $installed_size
arch = $pkgarch
license = Apache-2.0
depend = ffmpeg
depend = alsa-lib
depend = gcc-libs
depend = hicolor-icon-theme
optdepend = xdg-desktop-portal: native file picker
optdepend = noto-fonts-cjk: CJK font fallback
EOF

    cat >"$pkgdir/.INSTALL" <<'EOF'
post_install() {
    update-desktop-database -q /usr/share/applications 2>/dev/null || :
    gtk-update-icon-cache -q -t /usr/share/icons/hicolor 2>/dev/null || :
}
post_upgrade() {
    post_install
}
post_remove() {
    update-desktop-database -q /usr/share/applications 2>/dev/null || :
}
EOF

    # .MTREE is optional for pacman, but it enables `pacman -Qkk` file checks.
    if ! (
        cd "$pkgdir" &&
            bsdtar -czf .MTREE --format=mtree \
                --uid 0 --gid 0 --uname root --gname root \
                --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
                .PKGINFO .INSTALL usr
    ); then
        rm -f "$pkgdir/.MTREE"
    fi

    out="$outdir/hotview-${version}-${pkgrel}-${pkgarch}.pkg.tar.zst"
    members=".PKGINFO .INSTALL usr"
    if [ -f "$pkgdir/.MTREE" ]; then
        members=".PKGINFO .INSTALL .MTREE usr"
    fi
    # shellcheck disable=SC2086 # members is a deliberately split file list
    (
        cd "$pkgdir" &&
            bsdtar --format=ustar --uid 0 --gid 0 --uname root --gname root \
                -cf - $members |
            zstd -q -19 -T0 -o "$out"
    )

    printf '%s\n' "$out"
}

# ---------------------------------------------------------------------------
# Debian / Ubuntu package (.deb)
# ---------------------------------------------------------------------------
build_debian() {
    command -v ar >/dev/null 2>&1 || {
        echo "error: ar (binutils) is required for .deb packages" >&2
        exit 1
    }

    debroot="$tmp/deb"
    control="$tmp/control"
    mkdir -p "$debroot" "$control"
    cp -a "$stage/." "$debroot/"

    installed_size=$(du -sk "$debroot/usr" | awk '{print $1}')

    # Derive the real glibc floor from the symbol versions the binary needs
    # instead of hard-coding a guess that could be wrong on the next runner.
    min_glibc=$(objdump -T "$binary" 2>/dev/null |
        grep -oE 'GLIBC_[0-9]+\.[0-9]+' |
        sed 's/GLIBC_//' | sort -V | tail -n 1)
    [ -n "$min_glibc" ] || min_glibc=2.39

    cat >"$control/control" <<EOF
Package: hotview
Version: $version
Section: graphics
Priority: optional
Architecture: $debarch
Maintainer: Hotsteel <hotsteel2901@users.noreply.github.com>
Installed-Size: $installed_size
Depends: ffmpeg, libasound2t64 | libasound2, libgcc-s1, libstdc++6, libc6 (>= $min_glibc), libx11-6, libxext6, libxfixes3, libxcb1
Recommends: libvulkan1, libegl1, xdg-desktop-portal, fonts-noto-cjk, hicolor-icon-theme
Homepage: https://github.com/Hotsteel2901/Hotview
Description: Fast image and video viewer with GPU rendering
 Hotview is a photo and video viewer built on a Rust core: wgpu renders
 on the GPU while FFmpeg decodes common image and video formats.
 .
 Features: lazy thumbnail grid, zoom/pan/rotate/flip, animated GIF and
 WebP playback, video with audio, five UI languages.
EOF

    (
        cd "$debroot" &&
            find usr -type f -print0 | sort -z | xargs -0 md5sum
    ) >"$control/md5sums"

    printf '2.0\n' >"$tmp/debian-binary"
    tar --owner=0 --group=0 --numeric-owner -czf "$tmp/control.tar.gz" -C "$control" .
    tar --owner=0 --group=0 --numeric-owner -czf "$tmp/data.tar.gz" -C "$debroot" .

    out="$outdir/hotview_${version}_${debarch}.deb"
    rm -f "$out"
    (
        cd "$tmp" &&
            ar rcD "$out" debian-binary control.tar.gz data.tar.gz
    )

    printf '%s\n' "$out"
}

if [ "$fmt" = arch ]; then
    build_arch
else
    build_debian
fi
