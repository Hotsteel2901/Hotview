//! Multi-language strings for Hotview desktop (中文 / English / 日本語 / Deutsch / Русский),
//! matching the Android app and landing page.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LanguagePref {
    Auto,
    Zh,
    En,
    Ja,
    De,
    Ru,
}

impl LanguagePref {
    pub const ALL: [LanguagePref; 6] = [
        LanguagePref::Auto,
        LanguagePref::Zh,
        LanguagePref::En,
        LanguagePref::Ja,
        LanguagePref::De,
        LanguagePref::Ru,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::Zh => "zh",
            Self::En => "en",
            Self::Ja => "ja",
            Self::De => "de",
            Self::Ru => "ru",
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code.trim().to_ascii_lowercase().as_str() {
            "zh" | "zh-cn" | "zh-tw" | "zh-hk" => Self::Zh,
            "en" | "en-us" | "en-gb" => Self::En,
            "ja" | "ja-jp" => Self::Ja,
            "de" | "de-de" => Self::De,
            "ru" | "ru-ru" => Self::Ru,
            _ => Self::Auto,
        }
    }

    pub fn label(self, current: Lang) -> &'static str {
        match self {
            Self::Auto => strings(current).lang_system,
            Self::Zh => "中文",
            Self::En => "English",
            Self::Ja => "日本語",
            Self::De => "Deutsch",
            Self::Ru => "Русский",
        }
    }

    pub fn resolve(self, has_cjk_font: bool) -> Lang {
        let lang = match self {
            Self::Auto => detect_system_lang(),
            Self::Zh => Lang::Zh,
            Self::En => Lang::En,
            Self::Ja => Lang::Ja,
            Self::De => Lang::De,
            Self::Ru => Lang::Ru,
        };
        if !has_cjk_font && matches!(lang, Lang::Zh | Lang::Ja) {
            Lang::En
        } else {
            lang
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    Zh,
    En,
    Ja,
    De,
    Ru,
}

fn detect_system_lang() -> Lang {
    for key in ["LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"] {
        if let Ok(val) = std::env::var(key) {
            let lower = val.to_ascii_lowercase();
            if lower.starts_with("zh") {
                return Lang::Zh;
            }
            if lower.starts_with("ja") {
                return Lang::Ja;
            }
            if lower.starts_with("de") {
                return Lang::De;
            }
            if lower.starts_with("ru") {
                return Lang::Ru;
            }
            if lower.starts_with("en") {
                return Lang::En;
            }
        }
    }
    Lang::En
}

